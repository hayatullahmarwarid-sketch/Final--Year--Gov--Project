/** Status pill on dashboard and lists — maps API-style status to localized label. */
export function inspectorDashboardStatusText(lang: InspectorLang, status: TaskStatus): string {
  const t = INSPECTOR_TRANSLATIONS[lang];
  switch (status) {
    case 'assigned':
      return t.assigned;
    case 'in-progress':
      return t.inProgress;
    case 'overdue':
      return t.overdue;
    case 'draft':
      return t.draftLabelShort;
    case 'completed':
      return t.completed;
    case 'returned':
      return t.returnedLabelShort;
    default:
      return status;
  }
}

export function inspectorPriorityLabel(lang: InspectorLang, priority: 'high' | 'medium' | 'low'): string {
  const t = INSPECTOR_TRANSLATIONS[lang];
  if (priority === 'high') return t.priHigh;
  if (priority === 'medium') return t.priMedium;
  return t.priLow;
}
